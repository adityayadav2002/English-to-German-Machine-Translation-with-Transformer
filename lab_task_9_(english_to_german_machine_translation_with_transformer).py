import os
import torch
import matplotlib.pyplot as plt
import seaborn as sns
from transformers import AutoTokenizer, AutoModelForSeq2SeqLM

# Step 1️ — Load fine-tuned model & tokenizer
model_path = "./fine_tuned_en_de_transformer"

if not os.path.exists(model_path):
    raise ValueError(f" Model path not found: {model_path}\nTrain and save your model first!")

model = AutoModelForSeq2SeqLM.from_pretrained(model_path, attn_implementation="eager")
tokenizer = AutoTokenizer.from_pretrained(model_path)

# Step 2️ — Input sentence
src_text = "The transformer model is powerful for language translation."
inputs = tokenizer(src_text, return_tensors="pt")

# Step 3️ — Generate output with attentions
with torch.no_grad():
    outputs = model.generate(
        **inputs,
        max_new_tokens=40,
        output_attentions=True,
        return_dict_in_generate=True
    )

# Step 4️ — Decode tokens
tgt_tokens = tokenizer.convert_ids_to_tokens(outputs.sequences[0])
src_tokens = tokenizer.convert_ids_to_tokens(inputs["input_ids"][0])

# Step 5️ — Collect and average cross-attentions correctly
cross_att = outputs.cross_attentions  # list of length = decoding steps
# Each element = tuple(num_layers) → (num_heads, tgt_len=1, src_len)

# Stack attentions: (steps, layers, heads, 1, src_len)
att_per_layer = []
for layer_idx in range(len(cross_att[0])):  # loop over layers
    layer_stack = torch.stack([step[layer_idx] for step in cross_att], dim=0)  # (steps, heads, 1, src_len)
    att_per_layer.append(layer_stack)

# Combine layers → tensor (layers, steps, heads, 1, src_len)
att_all = torch.stack(att_per_layer, dim=0)

# Step 6️ — Average across steps and heads
att_avg = att_all.mean(dim=(1, 2))  # → (layers, 1, src_len)

# Step 7️ — Pick middle layer, squeeze, and convert to numpy
layer = att_avg.shape[0] // 2
att_matrix = att_avg[layer].squeeze(0).cpu().numpy().reshape(1, -1)  # (tgt_len, src_len)

# Step 8️ — Truncate to match tokens
att_matrix = att_matrix[:, :len(src_tokens)]

# Step 9️ — Plot the attention heatmap
plt.figure(figsize=(12, 6))
sns.heatmap(
    att_matrix,
    xticklabels=src_tokens,
    yticklabels=tgt_tokens,
    cmap="viridis"
)
plt.title(" Encoder–Decoder Cross-Attention: German ↔ English", fontsize=13)
plt.xlabel("English Input Tokens →")
plt.ylabel("← German Output Tokens")
plt.tight_layout()
plt.show()