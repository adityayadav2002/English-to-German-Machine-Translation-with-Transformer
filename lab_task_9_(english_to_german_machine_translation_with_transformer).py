"""### 3. Pre-processing Function
We must tokenize both the English (input) and German (target) sentences. For seq2seq models, the tokenized target sentences are assigned to the `labels` key.
"""

# Part 3: Pre-processing Function
# -------------------------------

# Define maximum sequence lengths (you can tune these)
max_source_length = 128   # for English sentences
max_target_length = 128   # for German translations

def preprocess_function(examples):
    """
    Tokenize English (source) and German (target) sentences.
    For seq2seq models:
      - 'input_ids' correspond to English tokens
      - 'labels' correspond to German tokens
    """

    # Source = English sentences
    inputs = examples["en"]

    # Target = German sentences
    targets = examples["de"]

    # 1️ Tokenize source (English)
    model_inputs = tokenizer(
        inputs,
        max_length=max_source_length,
        truncation=True,
        padding="max_length"
    )

    # 2️ Tokenize target (German)
    # 'as_target_tokenizer()' ensures labels use same tokenization rules
    with tokenizer.as_target_tokenizer():
        labels = tokenizer(
            targets,
            max_length=max_target_length,
            truncation=True,
            padding="max_length"
        )

    # 3️ Add labels to model_inputs dictionary
    model_inputs["labels"] = labels["input_ids"]

    return model_inputs

