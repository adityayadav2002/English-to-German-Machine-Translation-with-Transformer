# Part 3.1: Define Evaluation Metric (BLEU)
# -----------------------------------------

import evaluate
import numpy as np

# Load the sacrebleu metric
bleu = evaluate.load("sacrebleu")

# Define function to compute BLEU during evaluation
def compute_metrics(eval_preds):
    preds, labels = eval_preds

    # Decode model predictions (from token IDs → text)
    decoded_preds = tokenizer.batch_decode(preds, skip_special_tokens=True)

    # Replace -100 in labels with pad_token_id (ignore tokens)
    labels = np.where(labels != -100, labels, tokenizer.pad_token_id)
    decoded_labels = tokenizer.batch_decode(labels, skip_special_tokens=True)

    # Compute BLEU score
    result = bleu.compute(predictions=decoded_preds, references=[[lbl] for lbl in decoded_labels])

    # Compute average generation length for logging
    prediction_lens = [np.count_nonzero(pred != tokenizer.pad_token_id) for pred in preds]
    result["gen_len"] = np.mean(prediction_lens)

    # Round only numerical values
    for k, v in result.items():
        if isinstance(v, (int, float)):
            result[k] = round(v, 4)

    return result

print("✅ BLEU metric and compute_metrics() function ready!")

